import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join, relative, resolve } from 'node:path'
import * as p from '@clack/prompts'
import {
  type ExtensionSpec,
  type FilterSpec,
  type ParamsSpec,
  renderExtensionSource,
  renderFilterTypes,
  renderParamsTypes,
} from '@spree/sdk-core'
import type { Command } from 'commander'
import { execa } from 'execa'
import { parse } from 'yaml'

const APIS = ['store', 'admin', 'seller'] as const
type Api = (typeof APIS)[number]

/** The SDK an extension of each API extends, and imports shared types from. */
const SDKS: Record<Api, string> = {
  store: '@spree/sdk',
  admin: '@spree/admin-sdk',
  seller: '@spree/seller-sdk',
}

const HEADER =
  "// This file is generated by `spree sdk generate` from the extension's OpenAPI documents. Do not edit it; run the command again after changing an endpoint."

/** What `spree sdk generate` writes for each API, besides the response types. */
const OWN_OUTPUT = ['client.ts', 'params', 'filters.ts']
/** What `rake spree:sdk:serializer_types` writes for each API. */
const RESPONSE_OUTPUT = ['types', 'spree.ts']

const DEFAULT_OUT = 'src/generated'

interface GenerateOptions {
  extension?: string
  out?: string
  package?: string
  backend: boolean
  check?: boolean
}

/** `"spree"` in the package's package.json. */
interface PackageConfig {
  name?: string
  spree?: { extension?: string; out?: string }
}

/**
 * A package that extends Spree's SDKs generates its whole client from the
 * extension (or app) it is for: the OpenAPI documents its rswag specs write,
 * the response types its serializers give, and from those the request and
 * filter types and one SDK extension per resource.
 */
export function registerSdkCommand(program: Command): void {
  const sdk = program.command('sdk').description("Work with a package that extends Spree's SDKs")

  sdk
    .command('generate')
    .description(
      "Generate an SDK extension package's client and types from an extension's endpoints and serializers",
    )
    .option(
      '--extension <dir>',
      'the extension or app the package is for (default: "spree.extension" in package.json)',
    )
    .option(
      '--out <dir>',
      `where to write (default: "spree.out" in package.json, or ${DEFAULT_OUT})`,
    )
    .option(
      '--package <name>',
      "the package's name, for filter declarations (default: package.json's name)",
    )
    .option(
      '--no-backend',
      'use the committed openapi/*.yaml and response types instead of running the rake tasks',
    )
    .option('--check', 'write nothing; fail when the generated files are out of date')
    .action(async (options: GenerateOptions) => {
      const config = readPackage()
      const extension = options.extension ?? config.spree?.extension
      if (!extension) {
        p.log.error(
          'Name the extension with --extension, or as "spree": { "extension": "…" } in package.json.',
        )
        process.exitCode = 1
        return
      }
      const out = resolve(options.out ?? config.spree?.out ?? DEFAULT_OUT)
      const target = options.check ? mkdtempSync(join(tmpdir(), 'spree-sdk-')) : out

      try {
        if (options.check && !options.backend) copyResponseTypes(out, target)
        if (options.backend && !(await runBackend(resolve(extension), target))) {
          p.log.error(
            `The rake tasks in ${extension} failed (output above). Fix them, or pass --no-backend to use the committed documents.`,
          )
          process.exitCode = 1
          return
        }

        const written = generate(resolve(extension), target, options.package ?? config.name)
        if (written.length === 0) {
          p.log.error(
            `No OpenAPI documents in ${join(extension, 'openapi')}. Run \`rake spree:openapi:generate\` there first.`,
          )
          process.exitCode = 1
          return
        }

        if (options.check) {
          const stale = differences(target, out)
          if (stale.length) {
            p.log.error(`Out of date: ${stale.join(', ')}. Run \`spree sdk generate\`.`)
            process.exitCode = 1
          } else {
            p.log.success('Generated files are up to date.')
          }
          return
        }

        for (const { api, operations } of written) {
          p.log.success(
            `Wrote the ${api} client (${operations} operations) to ${relative(process.cwd(), join(out, api))}/`,
          )
        }
        p.log.info('Run this again after you change an endpoint or a serializer.')
      } finally {
        if (options.check) rmSync(target, { recursive: true, force: true })
      }
    })
}

/**
 * Writes, for each API the extension documents, `<out>/<api>/params/`,
 * `filters.ts` when it lists filters, and `client.ts`; and removes them for an
 * API it no longer documents. Each is rewritten from scratch, so an endpoint
 * that went away takes its types and its method with it.
 *
 * @returns the APIs written, with how many operations each client calls
 */
export function generate(extension: string, out: string, pkg?: string) {
  const written: { api: Api; operations: number }[] = []

  for (const api of APIS) {
    const file = join(extension, 'openapi', `${api}.yaml`)
    const dir = join(out, api)
    if (!existsSync(file)) {
      for (const entry of OWN_OUTPUT) rmSync(join(dir, entry), { recursive: true, force: true })
      continue
    }

    // Rendered before anything is removed, so a document that fails leaves
    // the previous files as they were.
    const spec = parse(readFileSync(file, 'utf8')) as ParamsSpec & FilterSpec & ExtensionSpec
    const params = renderParamsTypes(spec, { header: HEADER, sdk: SDKS[api] })
    const filters = spec.components?.['x-spree-filter-tables']
      ? renderFilterTypes(spec, api, { header: HEADER, module: pkg })
      : undefined
    const client = renderExtensionSource(spec, api, { header: HEADER, types: responseTypes(dir) })

    for (const entry of OWN_OUTPUT) rmSync(join(dir, entry), { recursive: true, force: true })
    mkdirSync(join(dir, 'params'), { recursive: true })
    for (const [name, source] of params) writeFileSync(join(dir, 'params', name), source)
    if (filters) writeFileSync(join(dir, 'filters.ts'), filters)
    if (client) writeFileSync(join(dir, 'client.ts'), client)

    written.push({ api, operations: client ? (client.match(/^ {2}\w+: \(/gm) ?? []).length : 0 })
  }
  return written
}

/** The response type names `rake spree:sdk:serializer_types` wrote for an API. */
export function responseTypes(dir: string): Set<string> {
  const index = join(dir, 'types', 'index.ts')
  if (!existsSync(index)) return new Set()

  const source = readFileSync(index, 'utf8')
  return new Set(
    [...source.matchAll(/export type \{([^}]+)\}/g)].flatMap((match) =>
      match[1].split(',').map((name) => name.trim()),
    ),
  )
}

/**
 * Runs the extension's rake tasks: its OpenAPI documents from its rswag
 * specs, then its response types into `out`. Outside the CLI's own bundle,
 * so the extension's Gemfile is the one used.
 */
async function runBackend(extension: string, out: string): Promise<boolean> {
  const env = Object.fromEntries(
    Object.entries(process.env).filter(
      ([key]) => !/^(BUNDLE_|BUNDLER_|RUBYOPT$|RUBYLIB$)/.test(key),
    ),
  )
  const result = await execa(
    'bundle',
    ['exec', 'rake', 'spree:openapi:generate', 'spree:sdk:serializer_types', `OUT=${out}`],
    { cwd: extension, env, extendEnv: false, stdio: 'inherit', reject: false },
  )
  return result.exitCode === 0
}

function copyResponseTypes(from: string, to: string): void {
  for (const api of APIS) {
    for (const entry of RESPONSE_OUTPUT) {
      const source = join(from, api, entry)
      if (existsSync(source)) cpSync(source, join(to, api, entry), { recursive: true })
    }
  }
}

/** The generated files that differ between two output folders. */
export function differences(generated: string, committed: string): string[] {
  const files = new Set([...listFiles(generated), ...listFiles(committed)])
  return [...files].sort().filter((file) => {
    const a = join(generated, file)
    const b = join(committed, file)
    return !existsSync(a) || !existsSync(b) || readFileSync(a, 'utf8') !== readFileSync(b, 'utf8')
  })
}

function listFiles(root: string): string[] {
  return APIS.flatMap((api) =>
    [...OWN_OUTPUT, ...RESPONSE_OUTPUT].flatMap((entry) => walk(root, join(api, entry))),
  )
}

function walk(root: string, path: string): string[] {
  const full = join(root, path)
  if (!existsSync(full)) return []
  try {
    return readdirSync(full).flatMap((name) => walk(root, join(path, name)))
  } catch {
    return [path]
  }
}

function readPackage(): PackageConfig {
  try {
    return JSON.parse(readFileSync('package.json', 'utf8')) as PackageConfig
  } catch {
    return {}
  }
}
