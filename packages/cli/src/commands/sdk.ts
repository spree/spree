import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { basename, join, relative, resolve } from 'node:path'
import * as p from '@clack/prompts'
import {
  type FilterSpec,
  type ParamsSpec,
  renderFilterTypes,
  renderParamsTypes,
} from '@spree/sdk-core'
import type { Command } from 'commander'
import { parse } from 'yaml'

const APIS = ['store', 'admin', 'seller'] as const
type Api = (typeof APIS)[number]

/** The SDK an extension of each API extends, and imports shared types from. */
const SDKS: Record<Api, string> = {
  store: '@spree/sdk',
  admin: '@spree/admin-sdk',
  seller: '@spree/seller-sdk',
}

const HEADER =
  "// This file is generated by `spree sdk types` from this package's OpenAPI documents. Do not edit it; run the command again after changing an endpoint."

interface TypesOptions {
  spec?: string[]
  out: string
  package?: string
}

/**
 * An extension documents its endpoints in its own `openapi/<api>.yaml`
 * (`rake spree:openapi:generate`). This writes the request body and list
 * filter types for a package of SDK extensions from those documents, with
 * the same renderers the SDKs generate their own types with.
 */
export function registerSdkCommand(program: Command): void {
  const sdk = program.command('sdk').description("Work with a package that extends Spree's SDKs")

  sdk
    .command('types')
    .description(
      "Generate request body and list filter types from an extension's OpenAPI documents",
    )
    .option(
      '--spec <file...>',
      'the OpenAPI documents to read, named after their API (default: openapi/store.yaml, openapi/admin.yaml and openapi/seller.yaml, those that exist)',
    )
    .option('--out <dir>', 'where to write the types, one folder per API', 'src/types')
    .option(
      '--package <name>',
      "the package's name, for the filter declarations an app writes (default: package.json's name)",
    )
    .action((options: TypesOptions) => {
      const specs =
        options.spec ??
        APIS.map((api) => join('openapi', `${api}.yaml`)).filter((file) => existsSync(file))
      if (specs.length === 0) {
        p.log.error('No OpenAPI documents found under openapi/. Pass them with --spec.')
        process.exitCode = 1
        return
      }

      const pkg = options.package ?? packageName()
      for (const file of specs) {
        const api = apiOf(file)
        if (!api) {
          p.log.error(
            `Cannot tell which API ${file} documents. Name it store.yaml, admin.yaml or seller.yaml.`,
          )
          process.exitCode = 1
          return
        }

        const { params, filters } = writeTypes(
          parse(readFileSync(resolve(file), 'utf8')),
          api,
          resolve(options.out, api),
          pkg,
        )
        p.log.success(
          `Wrote ${params} request types${filters ? ' and the list filters' : ''} for ${file} to ${relative(process.cwd(), resolve(options.out, api))}/`,
        )
      }
      p.log.info('Run this again after you change an endpoint.')
    })
}

/**
 * Writes `<out>/params/` (one file per request type and an index) and, when
 * the document lists filters (`filter_parameters_for`), `<out>/filters.ts`.
 * Both are rewritten from scratch, so a type whose endpoint went away goes
 * with it.
 *
 * @returns how many request types were written, and whether filters were
 */
export function writeTypes(
  spec: ParamsSpec & FilterSpec,
  api: Api,
  out: string,
  pkg?: string,
): { params: number; filters: boolean } {
  const params = renderParamsTypes(spec, { header: HEADER, sdk: SDKS[api] })
  const paramsDir = join(out, 'params')
  rmSync(paramsDir, { recursive: true, force: true })
  mkdirSync(paramsDir, { recursive: true })
  for (const [name, source] of params) writeFileSync(join(paramsDir, name), source)

  const filtersFile = join(out, 'filters.ts')
  const filters = Boolean(spec.components?.['x-spree-filter-tables'])
  if (filters) {
    writeFileSync(filtersFile, renderFilterTypes(spec, api, { header: HEADER, module: pkg }))
  } else {
    rmSync(filtersFile, { force: true })
  }
  return { params: params.size - 1, filters }
}

export function apiOf(file: string): Api | undefined {
  const name = basename(file).replace(/\.ya?ml$/, '')
  return APIS.find((api) => api === name)
}

function packageName(): string | undefined {
  try {
    return JSON.parse(readFileSync('package.json', 'utf8')).name
  } catch {
    return undefined
  }
}
