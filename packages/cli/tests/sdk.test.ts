import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { Command } from 'commander'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { stringify } from 'yaml'
import { apiOf, registerSdkCommand } from '../src/commands/sdk'

vi.mock('@clack/prompts', () => ({ log: { success: vi.fn(), error: vi.fn(), info: vi.fn() } }))

const predicates = {
  text: [
    'eq',
    'not_eq',
    'in',
    'not_in',
    'cont',
    'i_cont',
    'not_cont',
    'start',
    'end',
    'null',
    'not_null',
    'present',
    'blank',
  ],
  decimal: ['eq', 'not_eq', 'in', 'not_in', 'lt', 'lteq', 'gt', 'gteq', 'null', 'not_null'],
  integer: ['eq', 'not_eq', 'in', 'not_in', 'lt', 'lteq', 'gt', 'gteq', 'null', 'not_null'],
  date: ['eq', 'not_eq', 'in', 'not_in', 'lt', 'lteq', 'gt', 'gteq', 'null', 'not_null'],
  datetime: ['eq', 'not_eq', 'in', 'not_in', 'lt', 'lteq', 'gt', 'gteq', 'null', 'not_null'],
  enum: ['eq', 'not_eq', 'in', 'not_in', 'null', 'not_null'],
  id: ['eq', 'not_eq', 'in', 'not_in', 'null', 'not_null'],
  type: ['eq', 'not_eq', 'in', 'not_in', 'null', 'not_null'],
  boolean: ['eq', 'not_eq', 'in', 'not_in', 'true', 'false', 'null'],
}

// An extension's admin document: one request body that uses a shared code
// list, and one list endpoint with filters.
const adminSpec = {
  paths: {
    '/api/v3/admin/quotes': {
      get: { 'x-spree-filters': { table: 'Quote', sortable: ['number', 'valid_until'] } },
    },
  },
  components: {
    schemas: {
      SendQuoteParams: {
        type: 'object',
        properties: {
          valid_until: { type: 'string', format: 'date', nullable: true },
          currency: { $ref: '#/components/schemas/CurrencyCode' },
        },
      },
      CurrencyCode: { type: 'string', enum: ['EUR', 'USD'] },
      Quote: { type: 'object', properties: { id: { type: 'string' } } },
    },
    'x-spree-filter-tables': {
      Quote: { attributes: { number: 'text', status: 'text' }, associations: {}, scopes: {} },
    },
    'x-spree-filter-predicates': predicates,
  },
}

const storeSpec = {
  paths: {},
  components: {
    schemas: { QuoteCreateParams: { type: 'object', properties: { note: { type: 'string' } } } },
  },
}

async function run(argv: string[]) {
  const program = new Command()
  registerSdkCommand(program)
  await program.parseAsync(['sdk', 'types', ...argv], { from: 'user' })
}

describe('spree sdk types', () => {
  let dir: string
  let cwd: string

  beforeEach(() => {
    vi.clearAllMocks()
    cwd = process.cwd()
    dir = mkdtempSync(join(tmpdir(), 'spree-sdk-types-'))
    process.chdir(dir)
    mkdirSync('openapi')
    writeFileSync('openapi/admin.yaml', stringify(adminSpec))
    writeFileSync('package.json', JSON.stringify({ name: 'my-quotes-extension' }))
  })

  afterEach(() => {
    process.chdir(cwd)
    process.exitCode = undefined
  })

  it('writes the request types, importing shared code lists from the extended SDK', async () => {
    await run([])

    const params = readFileSync(join(dir, 'src/types/admin/params/SendQuoteParams.ts'), 'utf8')
    expect(params).toContain('generated by `spree sdk types`')
    expect(params).toContain("import type { CurrencyCode } from '@spree/admin-sdk'")
    expect(params).toContain('valid_until?: string | null')
    expect(readFileSync(join(dir, 'src/types/admin/params/index.ts'), 'utf8')).toContain(
      "export type { SendQuoteParams } from './SendQuoteParams'",
    )
    expect(existsSync(join(dir, 'src/types/admin/params/Quote.ts'))).toBe(false)
  })

  it("writes the list filters on the extended SDK's building blocks, for the package's name", async () => {
    await run([])

    const filters = readFileSync(join(dir, 'src/types/admin/filters.ts'), 'utf8')
    expect(filters).toContain("import type * as Filter from '@spree/admin-sdk'")
    expect(filters).not.toContain('@spree/sdk-core')
    expect(filters).toContain("declare module 'my-quotes-extension'")
    expect(filters).toContain('export type QuoteFilters')
    expect(filters).toContain("'number' | 'valid_until'")
  })

  it('writes one folder per document, and no filters for a document without them', async () => {
    writeFileSync('openapi/store.yaml', stringify(storeSpec))

    await run(['--out', 'types'])

    expect(readFileSync(join(dir, 'types/store/params/QuoteCreateParams.ts'), 'utf8')).toContain(
      'note?: string',
    )
    expect(existsSync(join(dir, 'types/store/filters.ts'))).toBe(false)
    expect(existsSync(join(dir, 'types/admin/filters.ts'))).toBe(true)
  })

  it('removes the types of an endpoint that went away', async () => {
    await run([])
    writeFileSync('openapi/admin.yaml', stringify({ ...adminSpec, components: { schemas: {} } }))

    await run([])

    expect(existsSync(join(dir, 'src/types/admin/params/SendQuoteParams.ts'))).toBe(false)
    expect(existsSync(join(dir, 'src/types/admin/filters.ts'))).toBe(false)
  })

  it('says so when there is no document to read', async () => {
    await run(['--spec', 'openapi/quotes.yaml'])

    expect(process.exitCode).toBe(1)
  })

  it('names the API after the document', () => {
    expect(apiOf('openapi/admin.yaml')).toBe('admin')
    expect(apiOf('/x/store.yml')).toBe('store')
    expect(apiOf('openapi/quotes.yaml')).toBeUndefined()
  })
})
