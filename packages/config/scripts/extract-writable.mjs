// Extracts, from the generated Admin API spec, the attributes each resource
// the configurator manages accepts on create and update, with their types.
// Sections build their file schema and their request bodies from this, so
// the configurator writes exactly what the API documents.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'
import { RESOURCES } from './resources.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const spec = parse(readFileSync(resolve(root, '../../docs/api-reference/admin.yaml'), 'utf-8'))

/** The parts of a property schema the configurator reads. */
function slim(property) {
  const out = {}
  for (const key of ['type', 'format', 'nullable', 'enum', 'deprecated']) {
    if (property[key] !== undefined) out[key] = property[key]
  }
  if (property.items?.type) out.items = { type: property.items.type }
  return out
}

/** A schema with any `$ref` (or single-entry `allOf`) followed to the component it names. */
function dereference(schema) {
  const ref = schema?.$ref ?? (schema?.allOf?.length === 1 ? schema.allOf[0].$ref : undefined)
  if (!ref) return schema
  const component = spec.components.schemas[ref.split('/').pop()]
  return { ...component, nullable: schema.nullable ?? component.nullable }
}

function bodyOf(operation) {
  const schema = dereference(operation?.requestBody?.content?.['application/json']?.schema)
  if (!schema?.properties) return null
  return {
    properties: Object.fromEntries(
      Object.entries(schema.properties).map(([name, property]) => [
        name,
        slim(dereference(property)),
      ]),
    ),
    required: schema.required ?? [],
  }
}

const out = {}
for (const resource of RESOURCES) {
  const collection = spec.paths[`/api/v3/admin/${resource}`] ?? {}
  const member = spec.paths[`/api/v3/admin/${resource}/{id}`] ?? {}
  const create = bodyOf(collection.post)
  const update = bodyOf(member.patch ?? collection.patch)
  if (!create && !update) throw new Error(`admin.yaml documents no request body for ${resource}`)
  out[resource] = { create, update }
}

const target = resolve(root, 'src/generated/writable.ts')
const content = `// Generated by scripts/extract-writable.mjs from docs/api-reference/admin.yaml — do not edit.\nexport const WRITABLE = ${JSON.stringify(out, null, 2)} as const\n`
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, content)
