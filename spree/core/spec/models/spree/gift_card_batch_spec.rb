require 'spec_helper'

RSpec.describe Spree::GiftCardBatch, type: :model do
  describe 'lifecycle events', events: true do
    let(:gift_card_batch_attrs) { { codes_count: 2, prefix: 'batch_', amount: 10 } }

    describe 'gift_card_batch.created' do
      it 'publishes created event when record is created' do
        record = build(:gift_card_batch, gift_card_batch_attrs)
        expect(record).to receive(:publish_event).with('gift_card_batch.created')
        allow(record).to receive(:publish_event).with(anything)

        record.save!
      end
    end

    describe 'gift_card.created' do
      let(:published) { [] }

      before do
        Spree::Events.subscribe('gift_card.created', async: false) { |event| published << event.payload['id'] }
        Spree::Events.activate!
      end

      after { Spree::Events.reset! }

      it 'publishes one event per gift card created in the batch' do
        batch = create(:gift_card_batch, gift_card_batch_attrs.merge(codes_count: 3))

        expect(batch.gift_cards.count).to eq(3)
        expect(published).to match_array(batch.gift_cards.map(&:prefixed_id))
      end

      # A batch card's payload is the one a gift card created on its own
      # publishes from its after_commit callback: nothing more, nothing less.
      it 'carries the same payload a single gift card create publishes' do
        payloads = Hash.new { |hash, key| hash[key] = [] }
        Spree::Events.subscribe('gift_card.created', async: false) { |event| payloads[event.payload['id']] << event.payload }
        Spree::Events.activate!

        gift_card = create(:gift_card_batch, gift_card_batch_attrs).gift_cards.first
        gift_card.send(:publish_create_event)

        batch_payload, single_payload = payloads.fetch(gift_card.prefixed_id)
        expect(batch_payload).to eq(single_payload)
      end

      it 'publishes one event per gift card generated by the background job' do
        batch = create(:gift_card_batch, gift_card_batch_attrs)
        batch.update_column(:codes_count, 4)
        published.clear

        Spree::GiftCards::BulkGenerateJob.perform_now(batch.id)

        expect(batch.gift_cards.count).to eq(4)
        expect(published.size).to eq(2)
        expect(published).to all(start_with('gc_'))
      end

      it 'publishes nothing while lifecycle events are disabled' do
        Spree::Events.disable_lifecycle { create(:gift_card_batch, gift_card_batch_attrs) }

        expect(published).to be_empty
      end
    end

    describe 'gift_card_batch.updated' do
      it 'publishes updated event when record is updated' do
        record = create(:gift_card_batch, gift_card_batch_attrs)
        expect(record).to receive(:publish_event).with('gift_card_batch.updated')
        allow(record).to receive(:publish_event).with(anything)

        travel(1.minute) do
          record.update_attribute(:updated_at, Time.current)
        end
      end
    end

    describe 'gift_card_batch.deleted' do
      it 'publishes deleted event when record is destroyed' do
        record = create(:gift_card_batch, gift_card_batch_attrs)
        expect(record).to receive(:publish_event).with('gift_card_batch.deleted', kind_of(Hash))
        allow(record).to receive(:publish_event).with(anything)

        record.destroy!
      end
    end
  end

  describe '#amount=' do
    it 'stores a canonical decimal exactly under a comma-decimal locale' do
      gift_card_batch = build(:gift_card_batch, codes_count: 2, prefix: 'batch_')
      I18n.with_locale(:nl) { gift_card_batch.amount = '49.50' }
      expect(gift_card_batch.amount).to eq(BigDecimal('49.50'))
    end
  end

  describe '#create_gift_cards' do
    subject(:gift_card_batch) { build(:gift_card_batch, codes_count: 2, prefix: 'batch_', amount: 10) }

    it 'generates gift cards' do
      gift_card_batch.save

      expect(gift_card_batch.gift_cards.count).to eq 2

      expect(gift_card_batch.gift_cards.pluck(:amount).uniq).to eq [gift_card_batch.amount]
      expect(gift_card_batch.gift_cards.pluck(:expires_at).uniq).to eq [gift_card_batch.expires_at]
      expect(gift_card_batch.gift_cards.take.code).to match(/batch_/)
    end

    it 'tops the batch up when a code is taken between the check and the insert' do
      existing = create(:gift_card, code: 'batch_taken')
      allow(gift_card_batch).to receive(:generate_codes).and_wrap_original do |original, count, **opts|
        opts[:taken].empty? ? ['batch_taken', *original.call(count - 1, **opts)] : original.call(count, **opts)
      end

      gift_card_batch.save!

      expect(gift_card_batch.gift_cards.count).to eq(2)
      expect(gift_card_batch.gift_cards).not_to include(existing)
    end
  end

  describe '#generate_codes' do
    subject(:gift_card_batch) { create(:gift_card_batch, codes_count: 1, prefix: 'batch_', amount: 10) }

    it 'returns the requested number of unique, prefixed codes' do
      codes = gift_card_batch.generate_codes(5)

      expect(codes.size).to eq(5)
      expect(codes.uniq.size).to eq(5)
      expect(codes).to all(start_with('batch_'))
    end

    it 'skips codes already used by a gift card' do
      taken = gift_card_batch.gift_cards.first.code
      allow(SecureRandom).to receive(:hex).and_return(taken.delete_prefix('batch_'), 'abcdef0123456789')

      expect(gift_card_batch.generate_codes(1)).to eq(['batch_abcdef0123456789'])
    end
  end

  describe 'code generation limits' do
    subject(:gift_card_batch) { build(:gift_card_batch, codes_count: 2, prefix: 'batch_', amount: 10) }

    it 'rejects a prefix that leaves codes no room in the column' do
      gift_card_batch.prefix = 'x' * (described_class::MAX_PREFIX_LENGTH + 1)

      expect(gift_card_batch).not_to be_valid
      expect(gift_card_batch.errors[:prefix]).to be_present
    end

    it 'raises instead of spinning when inserted cards keep going missing' do
      allow(Spree::GiftCard).to receive(:insert_all)

      expect { gift_card_batch.save! }.to raise_error(described_class::CodeGenerationError, /2 card\(s\) short/)
      # A round that inserts nothing stops at once rather than using every attempt.
      expect(Spree::GiftCard).to have_received(:insert_all).once
      expect(described_class.count).to eq(0)
    end

    it 'gives up after MAX_CODE_ATTEMPTS rounds that each insert only part of the batch' do
      gift_card_batch.codes_count = described_class::MAX_CODE_ATTEMPTS + 2
      allow(Spree::GiftCard).to(receive(:insert_all).and_wrap_original { |original, rows| original.call(rows.first(1)) })

      expect { gift_card_batch.save! }.to raise_error(described_class::CodeGenerationError, /2 card\(s\) short/)
      expect(Spree::GiftCard).to have_received(:insert_all).exactly(described_class::MAX_CODE_ATTEMPTS).times
    end

    it 'raises instead of spinning when every generated code is taken' do
      existing = create(:gift_card_batch, codes_count: 1, prefix: 'batch_', amount: 10)
      allow(SecureRandom).to receive(:hex).and_return(existing.gift_cards.first.code.delete_prefix('batch_'))

      expect { existing.generate_codes(1) }.to raise_error(described_class::CodeGenerationError)
    end
  end

  describe '#generate_gift_cards' do
    subject(:gift_card_batch) { build(:gift_card_batch, codes_count: 2, prefix: 'batch_', amount: 10) }

    context 'when codes count is less than 500' do
      it 'generates gift cards' do
        expect(gift_card_batch).to receive(:create_gift_cards)

        gift_card_batch.save
      end
    end

    context 'when codes count is greater than 500' do
      before { gift_card_batch.codes_count = 501 }

      it 'enqueues a job' do
        expect(Spree::GiftCards::BulkGenerateJob).to receive(:perform_later).with(kind_of(Integer), publish_events: false)

        gift_card_batch.save
      end
    end
  end
end
